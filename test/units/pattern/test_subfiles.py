    def test_simple_zip(self):

        data = (
            self.generate_random_buffer(200)
            + self.ZIP
            + self.generate_random_buffer(12)
            + self.PNG
            + self.generate_random_buffer(31)
            + self.TAR
            + self.generate_random_buffer(14)
        )
        test = data | self.load() | {bytes}
        goal = {self.ZIP, self.TAR, self.PNG}
        self.assertSetEqual(test, goal)

    def test_stored_file_inside_an_archive_is_suppressed(self):
        """
        The PNG in this archive is stored without compression, so it is also found by the PNG carver
        at a position inside the region that the ZIP carver reports. Only the containing archive is
        emitted, because the contained file is covered by it.
        """
        test = _ZIP_WITH_STORED_PNG | self.load() | [bytes]
        self.assertListEqual(test, [_ZIP_WITH_STORED_PNG])

    def test_stored_file_inside_an_archive_is_emitted_when_recursing(self):
        results = _ZIP_WITH_STORED_PNG | self.load(recursive=True) | []
        self.assertListEqual([item['start'] for item in results], [0, 41])
        self.assertEqual(bytes(results[0]), _ZIP_WITH_STORED_PNG)
        self.assertEqual(bytes(results[1]), _ZIP_WITH_STORED_PNG[41:41 + 376])

    def test_carvers_are_released_when_the_output_is_closed_early(self):
        from refinery.units.pattern.carve_zip import carve_zip
        with self.assertNoInstanceSurvives(carve_zip):
            with _ZIP_WITH_STORED_PNG | self.load(recursive=True) as carved:
                self.assertEqual(bytes(next(carved)), _ZIP_WITH_STORED_PNG)

    def test_a_file_following_an_archive_is_not_suppressed(self):
        """
        Coverage has to be limited to the region an item was carved from: a PNG that merely follows
        the archive is not contained in it and has to survive.
        """
        png = _ZIP_WITH_STORED_PNG[41:41 + 376]
        data = _ZIP_WITH_STORED_PNG + png
        test = data | self.load() | {bytes}
        self.assertSetEqual(test, {_ZIP_WITH_STORED_PNG, png})
