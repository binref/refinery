"""
What an emulation of an Inno Setup script reports and how it ends: the events that the emulators of
`refinery.lib.inno.emulator` yield, and the exceptions that end an emulation, which the script
cannot handle.
"""
from __future__ import annotations

from enum import StrEnum
from fractions import Fraction
