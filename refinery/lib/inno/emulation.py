class EntryLocation(NamedTuple):
    """
    An entry of an installer: its section, its number in that section, counted from zero, and the
    field that the location points at, if any.
    """
    section: EntrySection
    number: int
    field: EntryField | None = None

    def __str__(self):
        text = F'[{self.section}] entry {self.number}'
        if self.field is not None:
            text = F'{text}, {self.field}'
        return text


class NewScriptError(NamedTuple):
    """
    An event generated by `refinery.lib.inno.emulator.InnoSetupEmulator.emulate_installation` for
    each call of the script by Setup that ends with a script error which the script does not
    handle. It holds the event, the parameter of the entry or the directive that Setup evaluated,
    the arguments of an event, the message of the error, and for an entry where it is.
    """
    name: SetupEvent | PageEvent | ControlEvent | EntryParameter | YesNoDirective | TextDirective
    args: tuple
    message: str
    entry: EntryLocation | None = None

    def __str__(self):
        if (entry := self.entry) is not None:
            return F'script error in {self.name} of {entry}: {self.message}'
        return F'script error in {self.name}{self.args!r}: {self.message}'


class NewEmulationError(NamedTuple):
    """
    An event generated by `refinery.lib.inno.emulator.IFPSEmulator.emulate_function` for each call
    of an emulated function that fails with an error of the emulator rather than one of the
    script. The script sees the failure as an error that it can handle. It holds the name of the
    function and the message of the failure.
    """
    name: str
    message: str

    def __str__(self):
        return F'emulation of {self.name} failed: {self.message}'


class NewInstruction(NamedTuple):
    """
    An event generated by `refinery.lib.inno.emulator.IFPSEmulator.emulate_function` for each
    executed instruction.
    """
    function: Function
    instruction: Instruction
    offset: int
