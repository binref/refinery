"""
The programs that a default Windows installation keeps in the folders on its search path, by
folder, in the casing Windows shows them. The table is not exhaustive: it holds the programs that
scripts commonly run and is extended as needed.
"""


def make_win32_environment(
    username: str = 'Administrator',
    hostname: str | None = None,
) -> dict[str, str]:
    """
    Generate a default Windows environment variable dictionary.
    """
    if hostname is None:
        hostname = str(uuid4())
    return {
        key: value.format(h=hostname, u=username)
        for key, value in DEFAULT_ENVIRONMENT_TEMPLATE.items()
    }
